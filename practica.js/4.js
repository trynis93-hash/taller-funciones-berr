const califiacion = "A";
switch (califiacion.toUpperCase()) {
  case "A":
    console.log("EXELENTE");
    break;
  case "B":
    console.log("bueno");
    break;
  case "C":
    console.log("aceptable");
    break;
  case "D":
    console.log("insuficiente");
    break;
  default:
    console.log("calificacion no reconocida");
}
